-- =====================================================
-- Travel & Reimbursement Management - PostgreSQL Schema
-- Fully aligned with Java entity models in com.project.backend.model
-- Database: PostgreSQL
-- =====================================================

BEGIN;

-- ---------- 1. DEPARTMENT (model: Department.java) ----------
CREATE TABLE IF NOT EXISTS department (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    department_name  VARCHAR(100) NOT NULL,
    manager_id       BIGINT,                      -- FK -> users.id (added via ALTER TABLE below)
    CONSTRAINT pk_department PRIMARY KEY (id),
    CONSTRAINT uq_department_name UNIQUE (department_name)
);

-- ---------- 2. USERS (model: User.java) ----------
CREATE TABLE IF NOT EXISTS users (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name         VARCHAR(150) NOT NULL,
    age          INTEGER,
    gender       VARCHAR(20),
    email        VARCHAR(255) NOT NULL,
    designation  VARCHAR(100),
    manager_id   BIGINT,                          -- self-reference -> users.id
    dept_id      BIGINT,                          -- FK -> department.id
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT chk_users_age CHECK (age IS NULL OR age BETWEEN 18 AND 100),
    CONSTRAINT chk_users_gender CHECK (gender IS NULL OR gender IN ('MALE', 'FEMALE', 'OTHER')),
    CONSTRAINT chk_users_not_own_manager CHECK (manager_id IS NULL OR manager_id <> id),
    CONSTRAINT fk_users_manager FOREIGN KEY (manager_id)
        REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT fk_users_department FOREIGN KEY (dept_id)
        REFERENCES department (id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- Circular FK reference: department.manager_id -> users.id
ALTER TABLE department
    ADD CONSTRAINT fk_department_manager FOREIGN KEY (manager_id)
        REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL;

-- ---------- 3. USER_ACCOUNT (model: UserAuth.java) ----------
CREATE TABLE IF NOT EXISTS user_account (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id        BIGINT       NOT NULL,
    password_hash  VARCHAR(255) NOT NULL,
    role           VARCHAR(20)  NOT NULL,
    enabled        BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_user_account PRIMARY KEY (id),
    CONSTRAINT uq_user_account_user UNIQUE (user_id),
    CONSTRAINT chk_user_account_role CHECK (role IN ('ADMIN', 'MANAGER', 'FINANCE', 'EMPLOYEE')),
    CONSTRAINT fk_user_account_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON UPDATE CASCADE ON DELETE CASCADE
);

-- ---------- 4. TRAVEL_DETAIL (model: TravelDetail.java) ----------
-- Note: approvalFlow is mappedBy="travelDetail" on TravelDetail; owning FK travel_id resides on approval_flow
CREATE TABLE IF NOT EXISTS travel_detail (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    emp_id        BIGINT        NOT NULL,
    budget        NUMERIC(12,2) NOT NULL,
    purpose       TEXT          NOT NULL,
    status        VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',
    stay_days     INTEGER       NOT NULL,
    travel_date   DATE          NOT NULL,
    destination   VARCHAR(200)  NOT NULL,
    created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP,
    CONSTRAINT pk_travel_detail PRIMARY KEY (id),
    CONSTRAINT chk_travel_budget CHECK (budget >= 0),
    CONSTRAINT chk_travel_stay CHECK (stay_days >= 0),
    CONSTRAINT chk_travel_status CHECK (status IN ('DRAFT', 'PENDING', 'APPROVED', 'REJECTED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT fk_travel_emp FOREIGN KEY (emp_id)
        REFERENCES users (id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- ---------- 5. APPROVAL_FLOW (model: ApprovalFlow.java) ----------
-- One-to-one owning side with travel_detail (travel_id is UNIQUE)
CREATE TABLE IF NOT EXISTS approval_flow (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    travel_id    BIGINT      NOT NULL,
    manager_id   BIGINT      NOT NULL,
    status       VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    comment      TEXT,
    action_date  TIMESTAMP,
    CONSTRAINT pk_approval_flow PRIMARY KEY (id),
    CONSTRAINT uq_approval_flow_travel UNIQUE (travel_id),
    CONSTRAINT chk_approval_status CHECK (status IN ('DRAFT', 'PENDING', 'APPROVED', 'REJECTED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT fk_approval_travel FOREIGN KEY (travel_id)
        REFERENCES travel_detail (id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_approval_manager FOREIGN KEY (manager_id)
        REFERENCES users (id) ON UPDATE CASCADE ON DELETE RESTRICT
);

-- ---------- 6. REIMBURSEMENT (model: Reimbursement.java) ----------
-- One-to-one with travel_detail (travel_detail_id is UNIQUE)
CREATE TABLE IF NOT EXISTS reimbursement (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    emp_id            BIGINT        NOT NULL,
    travel_detail_id  BIGINT,
    status            VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',
    comment           TEXT,
    processed_at      TIMESTAMP,
    created_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_reimbursement PRIMARY KEY (id),
    CONSTRAINT uq_reimbursement_travel UNIQUE (travel_detail_id),
    CONSTRAINT chk_reimbursement_status CHECK (status IN ('DRAFT', 'PENDING', 'APPROVED', 'REJECTED', 'PAID')),
    CONSTRAINT fk_reimbursement_emp FOREIGN KEY (emp_id)
        REFERENCES users (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_reimbursement_travel FOREIGN KEY (travel_detail_id)
        REFERENCES travel_detail (id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- ---------- 7. EXPENSE_PROOF (model: ExpenseProof.java) ----------
-- Uses OffsetDateTime in Java -> TIMESTAMPTZ in PostgreSQL
CREATE TABLE IF NOT EXISTS expense_proof (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reimbursement_id    BIGINT        NOT NULL,
    uploaded_by         BIGINT,
    original_file_name  VARCHAR(255)  NOT NULL,
    stored_file_name    VARCHAR(255)  NOT NULL,
    file_path           VARCHAR(500)  NOT NULL,
    content_type        VARCHAR(100)  NOT NULL,
    file_size           BIGINT        NOT NULL,
    uploaded_at         TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_expense_proof PRIMARY KEY (id),
    CONSTRAINT uq_expense_proof_stored UNIQUE (stored_file_name),
    CONSTRAINT uq_expense_proof_path UNIQUE (file_path),
    CONSTRAINT fk_expense_proof_reimbursement FOREIGN KEY (reimbursement_id)
        REFERENCES reimbursement (id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_expense_proof_user FOREIGN KEY (uploaded_by)
        REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- ---------- 8. EXPENSE (model: Expense.java) ----------
-- Many expenses belong to one reimbursement (many-to-one)
-- One expense has one proof (one-to-one, expense_proof_id is UNIQUE)
CREATE TABLE IF NOT EXISTS expense (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reimbursement_id  BIGINT        NOT NULL,
    category          VARCHAR(30),
    amount            NUMERIC(12,2) NOT NULL,
    expense_proof_id  BIGINT,
    created_at        TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_expense PRIMARY KEY (id),
    CONSTRAINT uq_expense_proof_id UNIQUE (expense_proof_id),
    CONSTRAINT chk_expense_amount CHECK (amount > 0),
    CONSTRAINT chk_expense_category CHECK (category IS NULL OR category IN ('FOOD', 'STAY', 'TRANSPORT', 'MISCELLANEOUS')),
    CONSTRAINT fk_expense_reimbursement FOREIGN KEY (reimbursement_id)
        REFERENCES reimbursement (id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_expense_proof FOREIGN KEY (expense_proof_id)
        REFERENCES expense_proof (id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- ---------- 9. POLICY (model: Policy.java) ----------
CREATE TABLE IF NOT EXISTS policy (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name     VARCHAR(150) NOT NULL,
    type     VARCHAR(50)  NOT NULL,
    value    VARCHAR(255),
    comment  TEXT,
    active   BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_policy PRIMARY KEY (id),
    CONSTRAINT uq_policy_name UNIQUE (name),
    CONSTRAINT chk_policy_type CHECK (type IN (
        'BUDGET_LIMIT', 'TRAVEL_CLASS', 'EXPENSE_CATEGORY', 'EXPENSE_LIMIT',
        'STAY_LIMIT', 'APPROVAL_RULE', 'PROOF_REQUIRED', 'SUBMISSION_DEADLINE'
    ))
);

-- ---------- 10. AUDIT_LOG (model: AuditLog.java) ----------
CREATE TABLE IF NOT EXISTS audit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    entity_type   VARCHAR(50),
    entity_id     BIGINT,
    action        VARCHAR(50),
    performed_by  BIGINT,
    performed_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    details       TEXT,
    CONSTRAINT pk_audit_log PRIMARY KEY (id),
    CONSTRAINT fk_audit_user FOREIGN KEY (performed_by)
        REFERENCES users (id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- ---------- INDEXES ON FOREIGN KEYS & FILTER COLUMNS ----------
CREATE INDEX IF NOT EXISTS idx_users_manager               ON users (manager_id);
CREATE INDEX IF NOT EXISTS idx_users_dept                  ON users (dept_id);
CREATE INDEX IF NOT EXISTS idx_department_manager          ON department (manager_id);
CREATE INDEX IF NOT EXISTS idx_user_account_user           ON user_account (user_id);
CREATE INDEX IF NOT EXISTS idx_travel_emp                  ON travel_detail (emp_id);
CREATE INDEX IF NOT EXISTS idx_travel_status               ON travel_detail (status);
CREATE INDEX IF NOT EXISTS idx_approval_travel             ON approval_flow (travel_id);
CREATE INDEX IF NOT EXISTS idx_approval_manager            ON approval_flow (manager_id);
CREATE INDEX IF NOT EXISTS idx_reimbursement_emp           ON reimbursement (emp_id);
CREATE INDEX IF NOT EXISTS idx_reimbursement_travel        ON reimbursement (travel_detail_id);
CREATE INDEX IF NOT EXISTS idx_reimbursement_status        ON reimbursement (status);
CREATE INDEX IF NOT EXISTS idx_expense_proof_reimbursement ON expense_proof (reimbursement_id);
CREATE INDEX IF NOT EXISTS idx_expense_proof_uploaded_by   ON expense_proof (uploaded_by);
CREATE INDEX IF NOT EXISTS idx_expense_reimbursement       ON expense (reimbursement_id);
CREATE INDEX IF NOT EXISTS idx_expense_proof_id            ON expense (expense_proof_id);
CREATE INDEX IF NOT EXISTS idx_audit_performed_by          ON audit_log (performed_by);

-- ---------- SEED DATA: DEPARTMENTS ----------
INSERT INTO department (department_name, manager_id) VALUES
    ('Engineering', NULL),
    ('Product Management', NULL),
    ('Marketing', NULL),
    ('Sales', NULL),
    ('Human Resources', NULL),
    ('Finance & Accounting', NULL),
    ('Customer Support', NULL),
    ('Legal & Compliance', NULL),
    ('Information Technology', NULL),
    ('Research & Development', NULL)
ON CONFLICT (department_name) DO NOTHING;

COMMIT;

